function zombie(view, f) {
  const v = Z_VIEWS[view], cv = canvas(25)
  paint(cv, zLegs(view, f), 0, 19)
  if (v.behind) paint(cv, v.arm, 0, 11)
  paint(cv, Z_BODY[view], 0, 11)
  paint(cv, Z_HEAD[view], v.headX || 0, (v.headY || 0) + 1)
  if (!v.behind) paint(cv, v.arm, 0, 11)
  return gridText(cv)
}

